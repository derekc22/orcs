#!/usr/bin/env python3
"""Optimize actual placement/recovery from the proven frame-200 hand carry.

The zero-residual rollout exactly replays the 200 Hz v4 release controls.  A
small number of smooth, bounded position-target residual knots can alter that
motion and its suffix.  The object and floating base are never written after
initialization; all object motion is generated by MuJoCo contacts.
"""

from __future__ import annotations

import argparse
import itertools
import json
import time
from pathlib import Path

import mujoco
import numpy as np

from probe_flat_hand_grasp import build, smoothstep


GROUPS = (
    "left_hand",
    "right_hand",
    "wrist",
    "feet",
    "legs",
    "torso_pelvis",
    "other_robot",
)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--prefix", type=Path, required=True)
    parser.add_argument("--baseline", type=Path, required=True)
    parser.add_argument("--anchor-index", type=int, default=30)
    parser.add_argument(
        "--baseline-offset", type=int, default=0,
        help="Reference-frame offset into baseline controls at the splice.",
    )
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--horizon", type=int, default=100)
    parser.add_argument("--population", type=int, default=256)
    parser.add_argument("--elites", type=int, default=24)
    parser.add_argument("--generations", type=int, default=30)
    parser.add_argument("--initial-std", type=float, default=0.12)
    parser.add_argument("--free-initial-residual", action="store_true")
    parser.add_argument("--balance-only", action="store_true")
    parser.add_argument("--require-lift-frames", type=int, default=0)
    parser.add_argument("--require-lifted-path", type=float, default=0.0)
    parser.add_argument("--recovery-stance", type=Path)
    parser.add_argument("--recovery-start", type=int, default=25)
    parser.add_argument("--recovery-duration", type=float, default=5.0)
    parser.add_argument("--resume", type=Path)
    args = parser.parse_args()

    engine, generator = build(0.55)
    model = engine.model
    prefix = np.load(args.prefix)
    baseline = np.load(args.baseline)
    recovery_target = (
        None
        if args.recovery_stance is None
        else np.load(args.recovery_stance)["target"].copy()
    )
    i0 = args.anchor_index
    if i0 == 0:
        anchor_qpos = prefix["anchor_qpos"].copy()
        anchor_qvel = prefix["anchor_qvel"].copy()
    else:
        anchor_qpos = prefix["qpos"][i0 - 1].copy()
        anchor_qvel = prefix["qvel"][i0 - 1].copy()
    if args.baseline_offset == 0:
        baseline_qpos = baseline["anchor_qpos"]
        baseline_qvel = baseline["anchor_qvel"]
    else:
        baseline_qpos = baseline["qpos"][args.baseline_offset - 1]
        baseline_qvel = baseline["qvel"][args.baseline_offset - 1]
    if not np.array_equal(anchor_qpos, baseline_qpos):
        raise ValueError("baseline qpos does not exactly match prefix splice")
    if not np.array_equal(anchor_qvel, baseline_qvel):
        raise ValueError("baseline qvel does not exactly match prefix splice")
    if "ctrl_physics" not in baseline:
        raise ValueError("baseline must contain exact physics-rate controls")

    controlled = (
        np.asarray(generator.balance_actuators, dtype=int)
        if args.balance_only
        else np.arange(model.nu)
    )
    actuator_names = np.asarray(engine.joint_names)[engine.actuator_joint_indexes]
    object_geoms = set(map(int, engine.object_geoms))
    goal_position = engine.reference_object_pos[-1]
    goal_quaternion = engine.reference_object_quat[-1]
    ground_z = 0.18545216
    knot_frames = (
        np.asarray(
            [0.0, 0.25 * args.horizon, 0.60 * args.horizon, float(args.horizon)],
            dtype=np.float64,
        )
        if args.free_initial_residual
        else np.asarray(
            [
                0.0,
                0.15 * args.horizon,
                0.42 * args.horizon,
                0.70 * args.horizon,
                float(args.horizon),
            ],
            dtype=np.float64,
        )
    )

    def contact_group(geom: int) -> str:
        if geom == int(engine.hand_geoms[0]):
            return "left_hand"
        if geom == int(engine.hand_geoms[1]):
            return "right_hand"
        body = int(model.geom_bodyid[geom])
        name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_BODY, body) or ""
        if "wrist" in name:
            return "wrist"
        if "foot" in name or "ankle" in name:
            return "feet"
        if any(token in name for token in ("knee", "shin", "hip", "thigh")):
            return "legs"
        if any(token in name for token in ("torso", "pelvis", "waist")):
            return "torso_pelvis"
        return "other_robot"

    def baseline_control(step: int) -> np.ndarray:
        controls = baseline["ctrl_physics"]
        offset_steps = args.baseline_offset * engine.config.substeps
        if recovery_target is None:
            return controls[min(offset_steps + step, len(controls) - 1)]
        # Preserve v4 exactly through the selected post-step reference sample,
        # then smoothly recover toward a previously physical stance target.
        # This explicit 200 Hz construction avoids silently holding a 50 Hz
        # sample over controls that were originally generated every 5 ms.
        recovery_step = (args.recovery_start + 1) * engine.config.substeps
        if step < recovery_step:
            return controls[min(offset_steps + step, len(controls) - 1)]
        source = controls[
            min(offset_steps + recovery_step - 1, len(controls) - 1)
        ]
        frame = (step - recovery_step) / engine.config.substeps
        amount = smoothstep(frame / args.recovery_duration)
        return (1.0 - amount) * source + amount * recovery_target

    def residual_at(parameters: np.ndarray, frame: float) -> np.ndarray:
        free = parameters.reshape(3, len(controlled))
        knots = (
            np.vstack([free, np.zeros(len(controlled))])
            if args.free_initial_residual
            else np.vstack(
                [np.zeros(len(controlled)), free, np.zeros(len(controlled))]
            )
        )
        if frame >= knot_frames[-1]:
            return knots[-1]
        segment = int(np.searchsorted(knot_frames, frame, side="right") - 1)
        amount = smoothstep(
            (frame - knot_frames[segment])
            / (knot_frames[segment + 1] - knot_frames[segment])
        )
        return (1.0 - amount) * knots[segment] + amount * knots[segment + 1]

    def evaluate(parameters: np.ndarray, record: bool = False):
        data = mujoco.MjData(model)
        data.qpos[:] = anchor_qpos
        data.qvel[:] = anchor_qvel
        mujoco.mj_forward(model, data)
        impulses = {name: 0.0 for name in GROUPS}
        first_invalid = reason = None
        hand_frames = bilateral_frames = 0
        lift_flags: list[bool] = []
        lifted_hand_path = 0.0
        last_lifted_object = None
        maximum_lift = 0.0
        minimum_root = float(data.qpos[engine.robot_qpos + 2])
        maximum_tilt = 0.0
        minimum_position_error = float("inf")
        trace = {
            key: []
            for key in (
                "qpos",
                "qvel",
                "ctrl",
                "actuator_force",
                "hand_contact",
                "foot_contact",
                "object_position",
                "root_height",
                "torso_tilt",
                "object_impulse",
            )
        }
        ctrl_physics = []

        total_steps = args.horizon * engine.config.substeps
        for step in range(total_steps):
            frame = step / engine.config.substeps
            target = baseline_control(step).copy()
            target[controlled] += residual_at(parameters, frame)
            target = np.clip(
                target, model.actuator_ctrlrange[:, 0], model.actuator_ctrlrange[:, 1]
            )
            data.ctrl[:] = target
            if record:
                ctrl_physics.append(target.copy())
            mujoco.mj_step(model, data)
            physical = generator._physical(data)

            for contact_index in range(data.ncon):
                contact = data.contact[contact_index]
                first, second = int(contact.geom1), int(contact.geom2)
                if not ({first, second} & object_geoms):
                    continue
                other = second if first in object_geoms else first
                if int(model.geom_bodyid[other]) not in engine.robot_bodies:
                    continue
                force = np.zeros(6)
                mujoco.mj_contactForce(model, data, contact_index, force)
                impulses[contact_group(other)] += (
                    float(np.linalg.norm(force[:3])) * model.opt.timestep
                )

            object_position = data.qpos[
                engine.object_qpos : engine.object_qpos + 3
            ].copy()
            position_error = float(np.linalg.norm(object_position - goal_position))
            minimum_position_error = min(minimum_position_error, position_error)
            lift = float(object_position[2] - ground_z)
            maximum_lift = max(maximum_lift, lift)
            hand_count = int(np.sum(physical["hand_contact"]))
            if lift >= 0.05 and hand_count > 0:
                if last_lifted_object is not None:
                    lifted_hand_path += float(
                        np.linalg.norm(object_position - last_lifted_object)
                    )
                last_lifted_object = object_position.copy()
            else:
                last_lifted_object = None

            root_height = float(data.qpos[engine.robot_qpos + 2])
            minimum_root = min(minimum_root, root_height)
            maximum_tilt = max(maximum_tilt, float(physical["tilt"]))
            invalid = generator._invalid_reason(data, physical)
            disallowed = sum(
                impulses[name]
                for name in ("feet", "legs", "torso_pelvis", "other_robot")
            )
            if disallowed > 0.50 and invalid is None:
                invalid = "non_hand_object_impulse"

            if step % engine.config.substeps == engine.config.substeps - 1:
                hand_frames += int(hand_count > 0)
                bilateral_frames += int(hand_count == 2)
                lift_flags.append(lift >= 0.05 and hand_count > 0)
                if record:
                    trace["qpos"].append(data.qpos.copy())
                    trace["qvel"].append(data.qvel.copy())
                    trace["ctrl"].append(data.ctrl.copy())
                    trace["actuator_force"].append(data.actuator_force.copy())
                    trace["hand_contact"].append(physical["hand_contact"].copy())
                    trace["foot_contact"].append(physical["foot_contact"].copy())
                    trace["object_position"].append(object_position.copy())
                    trace["root_height"].append(root_height)
                    trace["torso_tilt"].append(float(physical["tilt"]))
                    trace["object_impulse"].append(
                        np.asarray(list(impulses.values()))
                    )
            if invalid is not None:
                first_invalid, reason = step, invalid
                break

        object_position = data.qpos[engine.object_qpos : engine.object_qpos + 3]
        object_quaternion = data.qpos[
            engine.object_qpos + 3 : engine.object_qpos + 7
        ]
        position_error = float(np.linalg.norm(object_position - goal_position))
        orientation_error = float(
            2.0
            * np.arccos(
                np.clip(abs(np.dot(object_quaternion, goal_quaternion)), 0.0, 1.0)
            )
        )
        object_speed = float(
            np.linalg.norm(data.qvel[engine.object_dof : engine.object_dof + 6])
        )
        root_height = float(data.qpos[engine.robot_qpos + 2])
        root_vertical_velocity = float(data.qvel[engine.robot_dof + 2])
        torso_tilt = float(physical["tilt"])
        foot_contacts = int(np.sum(physical["foot_contact"]))
        sustained_lift = max(
            (
                len(list(run))
                for value, run in itertools.groupby(lift_flags)
                if value
            ),
            default=0,
        )
        valid = first_invalid is None
        at_goal = position_error < 0.15 and orientation_error < 0.35
        recoverable = (
            valid
            and root_height >= 0.52
            and torso_tilt < np.deg2rad(40.0)
            and root_vertical_velocity > -0.10
            and foot_contacts == 2
        )
        contract = (
            sustained_lift >= args.require_lift_frames
            and lifted_hand_path >= args.require_lifted_path
        )
        recovery_cost = (
            20000.0 * max(0.0, 0.52 - root_height) ** 2
            + 3000.0 * max(0.0, torso_tilt - np.deg2rad(35.0)) ** 2
            + 2500.0 * max(0.0, -0.10 - root_vertical_velocity) ** 2
            + 1000.0 * float(foot_contacts == 0)
        )
        task_cost = (
            2800.0 * position_error**2
            + 500.0 * orientation_error**2
            + 55.0 * object_speed**2
            + 450.0 * minimum_position_error**2
            + recovery_cost
            + 12.0 * impulses["wrist"]
            + 0.4 * float(np.square(parameters).mean())
        )
        if valid and at_goal and recoverable and contract:
            rank = (0, task_cost)
        elif valid and contract and recoverable:
            rank = (1, task_cost)
        elif valid and contract:
            rank = (2, task_cost)
        elif contract:
            rank = (3, -int(first_invalid), task_cost)
        elif valid:
            rank = (
                4,
                max(0, args.require_lift_frames - sustained_lift),
                max(0.0, args.require_lifted_path - lifted_hand_path),
                -maximum_lift,
                task_cost,
            )
        else:
            rank = (
                5,
                max(0, args.require_lift_frames - sustained_lift),
                max(0.0, args.require_lifted_path - lifted_hand_path),
                -maximum_lift,
                -int(first_invalid),
                task_cost,
            )

        metrics = {
            "first_invalid_local_frame": (
                None if valid else first_invalid / engine.config.substeps
            ),
            "invalid_reason": reason,
            "valid_frames": step / engine.config.substeps,
            "maximum_lift_m": maximum_lift,
            "sustained_hand_supported_lift_frames_local": sustained_lift,
            "lifted_hand_mediated_path_m_local": lifted_hand_path,
            "hand_contact_frames": hand_frames,
            "bilateral_hand_contact_frames": bilateral_frames,
            "minimum_goal_position_error_m": minimum_position_error,
            "final_goal_position_error_m": position_error,
            "final_goal_orientation_error_rad": orientation_error,
            "final_object_speed": object_speed,
            "at_goal": at_goal,
            "minimum_root_height_m": minimum_root,
            "maximum_torso_tilt_deg": float(np.rad2deg(maximum_tilt)),
            "final_root_height_m": root_height,
            "final_root_vertical_velocity_m_s": root_vertical_velocity,
            "final_torso_tilt_deg": float(np.rad2deg(torso_tilt)),
            "final_foot_contacts": foot_contacts,
            "recoverable_terminal": bool(recoverable),
            "local_manipulation_contract": bool(contract),
            "object_impulse_ns": impulses,
            "cost": float(task_cost),
        }
        recorded = {key: np.asarray(value) for key, value in trace.items()}
        return rank, metrics, recorded, np.asarray(ctrl_physics)

    dimensions = 3 * len(controlled)
    per_actuator = np.asarray(
        [
            0.65
            if actuator in np.setdiff1d(np.arange(model.nu), generator.balance_actuators)
            and "wrist" not in actuator_names[actuator]
            else 0.45
            for actuator in controlled
        ]
    )
    bounds = np.tile(per_actuator, 3)
    mean = np.zeros(dimensions)
    std = args.initial_std * bounds
    best_parameters = mean.copy()
    start_generation = 0
    if args.resume is not None:
        checkpoint = np.load(args.resume)
        best_parameters = checkpoint["parameters"].copy()
        mean = checkpoint["mean"].copy()
        std = checkpoint["std"].copy()
        start_generation = int(checkpoint["generation"]) + 1

    rng = np.random.default_rng(19103)
    best = evaluate(best_parameters)
    history = []
    started = time.perf_counter()
    for generation in range(start_generation, args.generations):
        population = np.clip(
            rng.normal(mean, std, (args.population, dimensions)), -bounds, bounds
        )
        population[0] = best_parameters
        if len(population) > 1:
            population[1] = 0.0
        results = [evaluate(candidate) for candidate in population]
        order = sorted(range(len(population)), key=lambda index: results[index][0])
        if results[order[0]][0] < best[0]:
            best_parameters = population[order[0]].copy()
            best = results[order[0]]
        elite = population[order[: args.elites]]
        mean = 0.72 * elite.mean(0) + 0.28 * mean
        std = np.maximum(0.72 * elite.std(0) + 0.28 * std, 0.006)
        history.append({"generation": generation, **best[1]})
        print("GEN", generation, json.dumps(best[1]), flush=True)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        np.savez_compressed(
            args.output.with_name(args.output.name + "_checkpoint").with_suffix(
                ".npz"
            ),
            parameters=best_parameters,
            mean=mean,
            std=std,
            generation=generation,
        )

    _, metrics, trace, ctrl_physics = evaluate(best_parameters, record=True)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        args.output.with_suffix(".npz"),
        parameters=best_parameters,
        anchor_qpos=anchor_qpos,
        anchor_qvel=anchor_qvel,
        anchor_index=i0,
        knot_frames=knot_frames,
        controlled_actuators=controlled,
        ctrl_physics=ctrl_physics,
        **trace,
    )
    report = {
        "method": "physics-rate v4-residual direct placement and recovery",
        "prefix": str(args.prefix),
        "baseline": str(args.baseline),
        "baseline_offset": args.baseline_offset,
        "recovery_stance": (
            None if args.recovery_stance is None else str(args.recovery_stance)
        ),
        "recovery_start": args.recovery_start,
        "recovery_duration": args.recovery_duration,
        "dimensions": dimensions,
        "population": args.population,
        "generations": args.generations,
        "horizon_frames": args.horizon,
        "free_initial_residual": args.free_initial_residual,
        "balance_only": args.balance_only,
        "required_lift_frames": args.require_lift_frames,
        "required_lifted_path_m": args.require_lifted_path,
        "runtime_s": time.perf_counter() - started,
        "best": metrics,
        "history": history,
    }
    args.output.with_suffix(".json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
